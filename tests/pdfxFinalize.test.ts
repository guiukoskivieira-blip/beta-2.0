/**
 * Creates a synthetic PDF ready for full preparation -> finalization pipeline:
 * - 90x50 mm trim target (MediaBox 96x56 mm = 3mm bleed margin)
 * - 1 RGB raster image 10x10 px (FlateDecode)
 * - Missing OutputIntent
 * - Missing TrimBox/BleedBox
 */
async function createFixableTestPdf(): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const pageW = (96 * 72) / 25.4;
  const pageH = (56 * 72) / 25.4;
  const page = doc.addPage([pageW, pageH]);

  const rawRgb = new Uint8Array(10 * 10 * 3);
  for (let i = 0; i < rawRgb.length; i += 3) {
    rawRgb[i] = 255;
    rawRgb[i + 1] = 100;
    rawRgb[i + 2] = 50;
  }
  const flateBytes = pako.deflate(rawRgb);

  const imgDict = doc.context.obj({
    Type: 'XObject',
    Subtype: 'Image',
    Width: 10,
    Height: 10,
    BitsPerComponent: 8,
    ColorSpace: 'DeviceRGB',
    Filter: 'FlateDecode',
  });
  const imgStream = PDFRawStream.of(imgDict as any, flateBytes);
  const imgRef = doc.context.register(imgStream);

  page.node.set(
    PDFName.of('Resources'),
    doc.context.obj({ XObject: { Im1: imgRef } })
  );

  return await doc.save({ useObjectStreams: false });
}

test('1. End-to-End: Original -> Preparation -> Finalize -> Reopen -> Motor 1 -> verifiedPdfX = true', async () => {
  const originalBytes = await createFixableTestPdf();

  // Phase 2: Preparation
  const prepResult = await preparePdfForPdfx4(originalBytes, {
    profile: COMMERCIAL_PRINT_300DPI_PROFILE,
    allowFallbackSrgb: true,
    destinationIccPresetId: 'cgats_tr_001_swop',
  });

  assert.equal(prepResult.success, true);
  assert.equal(prepResult.status, 'prepared');
  assert.equal(prepResult.eligibleAfterPreparation.eligible, true);
  // Verified is STILL false in Phase 2
  assert.equal(prepResult.verifiedPdfX, false);
  assert.ok(prepResult.pdfBytes);

  // Phase 3: Finalization & Verification
  const finalizeResult: PdfxFinalizeResult = await finalizePdfx4Document(prepResult.pdfBytes!, {
    profile: COMMERCIAL_PRINT_300DPI_PROFILE,
    destinationIccPresetId: 'cgats_tr_001_swop',
    title: 'ArteCheck Teste PDF/X-4',
  });

  assert.equal(finalizeResult.success, true, 'Finalização deve ter sucesso');
  assert.equal(finalizeResult.declaredPdfX, 'PDF/X-4', 'declaredPdfX deve ser PDF/X-4');
  assert.equal(finalizeResult.verifiedPdfX, true, 'verifiedPdfX DEVE ser true após validação do arquivo serializado');
  assert.equal(finalizeResult.targetStandard, 'PDF/X-4');
  assert.ok(finalizeResult.finalizedPdfBytes, 'Buffer finalizado deve existir');
  assert.notEqual(finalizeResult.preparedSha256, finalizeResult.finalizedSha256);

  // Verify all 8 checks passed
  assert.equal(finalizeResult.checks.length, 8);
  assert.ok(finalizeResult.checks.every((c) => c.status === 'passed'));

  // Independent re-extraction of the generated bytes to confirm PDF/X-4 markers
  const reExtracted = await extractPdfStructure(finalizeResult.finalizedPdfBytes!);
  assert.equal(reExtracted.pdfxInfo?.isDeclaredPdfX, true);
  assert.ok(reExtracted.pdfxInfo?.declaredVersion?.includes('PDF/X-4'));
  assert.equal(reExtracted.pdfxInfo?.hasXmpMetadata, true);
  assert.ok(reExtracted.pdfxInfo?.xmpPdfxVersion?.includes('PDF/X-4'));
  assert.equal(reExtracted.colorSummary.hasRgb, false);
  assert.equal(reExtracted.colorSummary.hasCmyk, true);
});

